"""Known-null-face cone certificates for an isolated Gaussian oracle benchmark.

This file does NOT infer a face from data, supply GMS validity, choose c, or
replace the frozen UK test. Its immutable inputs are a known common projection
q of RUM and the product simplex, and a known n in the simplex normal cone.
The RUM critical cone is generated by A[:,h]-q with n'(A[:,h]-q)==0.

Numerical cone proposals are accepted only after an exact nonnegative primal
and an exactly polar dual bound agree to the declared tolerance. The special
dual repair uses the supplied exact exposed face; it is not a generic H-rep.
All coordinates, including simplex zero coordinates, remain in the metric.
"""
module CMUKnownFaceCones

using JuMP, OSQP, LinearAlgebra

export KnownFaceCone, cone_certificate!, simplex_critical_projection,
       critical_gap!, raw_normal, exact_basis, finite_gap_bound,
       product_simplex_projection, Q

const Q = Rational{BigInt}

qdot(x, y) = sum(x .* y; init=Q(0))
qnorm2(x) = qdot(x, x)

"""An exact integer basis for the affine differences of the listed columns."""
function exact_basis(A, indices)
    I = size(A, 1)
    base = first(indices)
    basis = Vector{Vector{BigInt}}()
    echelon = Vector{Vector{Q}}()
    pivots = Int[]
    columns = Int[]
    for h in indices
        v = BigInt.(A[:, h]) .- BigInt.(A[:, base])
        residual = Q.(v)
        for (u, pivot) in zip(echelon, pivots)
            residual .-= residual[pivot] .* u
        end
        pivot = findfirst(!iszero, residual)
        pivot === nothing && continue
        push!(basis, v)
        push!(echelon, residual ./ residual[pivot])
        push!(pivots, pivot)
        push!(columns, h)
    end
    B = isempty(basis) ? zeros(BigInt, I, 0) : reduce(hcat, basis)
    gram_inverse = isempty(basis) ? zeros(Q, 0, 0) : inv(Q.(transpose(B) * B))
    (; B, gram_inverse, columns, base)
end

function off_span(g, B, gram_inverse)
    isempty(B) && return copy(g), Q[]
    coefficients = gram_inverse * (transpose(B) * g)
    g .- B * coefficients, coefficients
end

"""Choose an explicit dyadic outward normal only at zero simplex coordinates.

Positive q coordinates have normal zero. At q_i==0, n_i=-strength<0.
Thus n belongs to the full product-simplex normal cone exactly. This is a
synthetic known-null construction, not a claim about estimated raw means.
"""
function raw_normal(q; strength=Q(1, 8))
    strength >= 0 || throw(ArgumentError("normal strength must be nonnegative"))
    [iszero(x) ? -Q(strength) : Q(0) for x in q]
end

"""A dyadic simplex normal with exact zero adding-up in every budget.

For k coordinates and Z zero coordinates, n_i=(Z-k*1{q_i=0})/denominator.
All positive coordinates have the same group normal, zero coordinates have a
strictly lower normal, and the raw null q+n still adds to one in every budget.
"""
function raw_normal(q, groups; denominator=64)
    denominator > 0 && ispow2(denominator) || error("normal denominator must be a positive power of two")
    n = zeros(Q, length(q))
    for group in groups
        k, Z = length(group), count(i -> iszero(q[i]), group)
        for i in group
            n[i] = Q(Z - k*Int(iszero(q[i])), denominator)
        end
        sum(n[group]) == 0 || error("raw normal lost exact budget adding-up")
    end
    n
end

mutable struct KnownFaceCone
    A::Matrix{Int8}
    q::Vector{Q}
    n::Vector{Q}
    groups::Vector{Vector{Int}}
    face::Vector{Int}
    retained::Vector{Int}
    eta::Vector{Q}
    eta_prices::Vector{Q}
    basis::Matrix{BigInt}
    gram_inverse::Matrix{Q}
    basis_columns::Vector{Int}
    basis_base::Int
    whole_face::Bool
    centroid_weights::Vector{Q}
    model::Union{Nothing,Model}
    z_variables::Vector{VariableRef}
    mass_variables::Vector{VariableRef}
    calls::Int
    solves::Int
end

function KnownFaceCone(A, q, groups; face=collect(axes(A, 2)),
        exposing_normal=zeros(Q, size(A, 1)), n=zeros(Q, size(A, 1)),
        centroid_weights=nothing)
    all(x -> x == 0 || x == 1, A) || error("RUM vertices must be binary incidence columns")
    A = Matrix{Int8}(A)
    q, n, eta = Q.(q), Q.(n), Q.(exposing_normal)
    groups = [Int.(group) for group in groups]
    I, H = size(A)
    length(q) == length(n) == length(eta) == I || error("coordinate mismatch")
    sort(reduce(vcat, groups)) == collect(1:I) || error("groups must partition coordinates")
    all(all(>=(0), q[group]) && sum(q[group]) == 1 for group in groups) ||
        error("known projection must lie in the product simplex")
    all(all(sum(A[group, h]) == 1 for group in groups) for h in 1:H) ||
        error("each RUM vertex must choose one patch per budget")
    for group in groups
        positive = filter(i -> q[i] > 0, group)
        c = n[first(positive)]
        all(n[i] == c for i in positive) || error("normal varies on positive coordinates")
        all(n[i] <= c for i in group) || error("normal is not a simplex normal")
    end
    face = sort(unique(Int.(face)))
    isempty(face) && error("known exposed face must be nonempty")
    exact_face_mean = [sum(Q(A[i, h]) for h in face) / length(face) for i in 1:I]
    # A positive mean of all listed face vertices and q must have the same zero
    # coordinates. Membership itself is separately supplied by the geometry's
    # exact positive mixture, verified below for whole-face or via span/normal.
    all(iszero(q[i]) == iszero(exact_face_mean[i]) for i in 1:I) ||
        error("q does not have the supplied face's relative-interior support")
    span = exact_basis(A, face)
    residual, _ = off_span(q .- Q.(A[:, first(face)]), span.B, span.gram_inverse)
    all(iszero, residual) || error("q is outside the supplied face affine hull")
    eta_prices = [qdot(eta, Q.(A[:, h]) .- q) for h in 1:H]
    whole_face = length(face) == H
    if whole_face
        all(iszero, eta_prices) || error("whole-face exposure must vanish")
    else
        all(iszero(eta_prices[h]) for h in face) || error("exposure misses a face vertex")
        all(eta_prices[h] < 0 for h in setdiff(1:H, face)) ||
            error("normal does not strictly expose exactly the supplied face")
    end
    nprices = [qdot(n, Q.(A[:, h]) .- q) for h in 1:H]
    all(<=(0), nprices) || error("normal fails the complete RUM support audit")
    retained = findall(iszero, nprices)
    all(h in retained for h in face) || error("critical slice lost a face generator")
    rho = centroid_weights === nothing ? Q[] : Q.(centroid_weights)
    if whole_face
        length(rho) == H && all(>(0), rho) && sum(rho) == 1 ||
            error("whole-face analytic cone requires a positive mixture on every column")
        Q.(A) * rho == q || error("whole-face exact mixture mismatch")
        model, z_variables, mass_variables = nothing, VariableRef[], VariableRef[]
    else
        # q must be known to be a strictly positive mixture of all face vertices;
        # caller passes this exact mixture through centroid_weights on that face.
        length(rho) == length(face) && all(>(0), rho) && sum(rho) == 1 ||
            error("exposed-face certificate requires exact positive face weights")
        Q.(A[:, face]) * rho == q || error("exposed-face exact mixture mismatch")
        model = Model(OSQP.Optimizer)
        set_silent(model)
        set_optimizer_attribute(model, "eps_abs", 1e-10)
        set_optimizer_attribute(model, "eps_rel", 1e-10)
        set_optimizer_attribute(model, "max_iter", 200000)
        set_optimizer_attribute(model, "polish", true)
        @variable(model, mass[1:length(retained)] >= 0)
        @variable(model, z[1:I])
        D = Float64.(A[:, retained]) .- Float64.(q)
        @constraint(model, [i=1:I], z[i] == sum(D[i, h] * mass[h] for h in eachindex(retained)))
        @objective(model, Min, sum(z[i]^2 for i in 1:I))
        z_variables, mass_variables = collect(z), collect(mass)
    end
    KnownFaceCone(A, q, n, groups, face, retained, eta, eta_prices,
        span.B, span.gram_inverse, span.columns, span.base, whole_face,
        rho, model, z_variables, mass_variables, 0, 0)
end

"""Exact ray prices, using one common integer denominator (never a tolerance).

Returns y'(A_h-q) for every retained generator. Int128 is used only when the
sum of absolute numerator values fits safely; otherwise arithmetic is BigInt.
"""
function ray_prices(y, cone::KnownFaceCone; indices=cone.retained)
    denominator_y = foldl(lcm, denominator.(y); init=big(1))
    yn = [numerator(x) * div(denominator_y, denominator(x)) for x in y]
    use128 = sum(abs, yn) <= typemax(Int128)
    yn_work = use128 ? Int128.(yn) : yn
    qprice = qdot(y, cone.q)
    [Q(sum((yn_work[i] for i in axes(cone.A, 1) if cone.A[i, h] != 0);
            init=use128 ? Int128(0) : big(0)), denominator_y) - qprice
     for h in indices]
end

function cone_certificate!(cone::KnownFaceCone, g; tolerance=2e-7,
        dyadic_bits=48, include_primitives=false)
    gq = Q.(g)
    length(gq) == length(cone.q) || error("Gaussian coordinate mismatch")
    all(isfinite, Float64.(gq)) || error("nonfinite direction")
    cone.calls += 1
    if cone.whole_face
        dual, coefficients = off_span(gq, cone.basis, cone.gram_inverse)
        z = gq .- dual
        signed = zeros(Q, size(cone.A, 2))
        for (h, c) in zip(cone.basis_columns, coefficients)
            signed[h] += c
            signed[cone.basis_base] -= c
        end
        shift = maximum(max(Q(0), -signed[h] / cone.centroid_weights[h])
                        for h in eachindex(signed))
        masses = signed .+ shift .* cone.centroid_weights
        all(>=(0), masses) || error("analytic cone primal is negative")
        Q.(cone.A) * masses .- cone.q .* sum(masses) == z ||
            error("analytic cone primal identity failed")
        all(iszero, ray_prices(dual, cone)) || error("analytic cone dual is not exactly orthogonal")
        loss = qnorm2(dual)
        return (; lower=loss, upper=loss, midpoint=Float64(loss), width=0.,
            max_polar_price=Q(0), repair_coefficient=Q(0), analytic=true,
            primal=include_primitives ? z : Q[], dual=include_primitives ? dual : Q[],
            masses=include_primitives ? masses : Q[])
    end
    model = cone.model
    for i in eachindex(gq)
        set_objective_coefficient(model, cone.z_variables[i], -2Float64(gq[i]))
    end
    optimize!(model)
    cone.solves += 1
    primal_status(model) == JuMP.MOI.FEASIBLE_POINT ||
        error("cone proposal failed: $(termination_status(model))")
    numeric_masses = value.(cone.mass_variables)
    all(isfinite, numeric_masses) || error("nonfinite cone masses")
    denominator_mass = big(1) << dyadic_bits
    counts = [max(big(0), round(BigInt, max(0., x) * Float64(denominator_mass)))
              for x in numeric_masses]
    masses = counts .// denominator_mass
    z = Q.(cone.A[:, cone.retained]) * masses .- cone.q .* sum(masses)
    residual = gq .- z
    dual, _ = off_span(residual, cone.basis, cone.gram_inverse)
    prices = ray_prices(dual, cone)
    repair = Q(0)
    for (h, price) in zip(cone.retained, prices)
        if iszero(cone.eta_prices[h])
            iszero(price) || error("face-span projection did not annihilate face price")
        elseif price > 0
            repair = max(repair, price / -cone.eta_prices[h])
        end
    end
    dual .+= repair .* cone.eta
    repaired_prices = ray_prices(dual, cone)
    all(<=(0), repaired_prices) || error("repaired cone dual is not exactly polar")
    upper = qnorm2(residual)
    lower = max(Q(0), 2qdot(gq, dual) - qnorm2(dual))
    lower <= upper || error("exact cone weak duality failed")
    width = Float64(upper - lower)
    width <= tolerance * max(1., Float64(qnorm2(gq))) ||
        error("cone certificate gap $width exceeds declared tolerance for the same direction")
    (; lower, upper, midpoint=Float64((lower + upper) / 2), width,
       max_polar_price=maximum(repaired_prices), repair_coefficient=repair, analytic=false,
       primal=include_primitives ? z : Q[], dual=include_primitives ? dual : Q[],
       masses=include_primitives ? masses : Q[])
end

"""Exact projection onto T_S(q) intersect n-perp, preserving all zeros.

Within each budget, positive q coordinates are free, zero q coordinates with
zero normal multiplier are nonnegative, and zero q coordinates with positive
multiplier are fixed at zero. A sorted active-set waterfill solves adding-up.
"""
function simplex_critical_projection(g, q, n, groups)
    g, q, n = Q.(g), Q.(q), Q.(n)
    z = zeros(Q, length(g))
    for group in groups
        free = [i for i in group if q[i] > 0]
        isempty(free) && error("simplex budget has no positive coordinate")
        normal_level = n[first(free)]
        all(n[i] == normal_level for i in free) || error("invalid normal on free coordinates")
        nonnegative = [i for i in group if iszero(q[i]) && n[i] == normal_level]
        fixed = [i for i in group if iszero(q[i]) && n[i] < normal_level]
        length(free) + length(nonnegative) + length(fixed) == length(group) ||
            error("invalid simplex normal multiplier")
        ordered = sort(nonnegative; by=i -> g[i], rev=true)
        active = Int[]
        theta = sum(g[free]) / length(free)
        for i in ordered
            g[i] > theta || break
            push!(active, i)
            theta = (sum(g[free]) + sum(g[active])) / (length(free) + length(active))
        end
        for i in free
            z[i] = g[i] - theta
        end
        for i in nonnegative
            z[i] = max(Q(0), g[i] - theta)
        end
        sum(z[group]) == 0 || error("exact critical-simplex adding-up failed")
        all(z[i] == 0 for i in fixed) || error("fixed normal coordinates moved")
    end
    (; point=z, loss=qnorm2(g .- z))
end

function critical_gap!(cone::KnownFaceCone, g; kwargs...)
    rum = cone_certificate!(cone, g; kwargs...)
    simplex = simplex_critical_projection(g, cone.q, cone.n, cone.groups)
    upper = rum.upper - simplex.loss
    upper >= 0 || error("certified RUM cone primal is outside the simplex critical cone")
    lower = max(Q(0), rum.lower - simplex.loss)
    (; lower, upper, midpoint=Float64((lower + upper) / 2),
       width=Float64(upper - lower), rum, simplex)
end

"""Exact finite product-simplex projection; no pre-clipping of a raw target."""
function product_simplex_projection(p, groups)
    p = Q.(p)
    projected = zeros(Q, length(p))
    for group in groups
        ordered = sort(group; by=i -> p[i], rev=true)
        total = Q(0)
        theta = Q(0)
        for (k, i) in enumerate(ordered)
            total += p[i]
            theta = (total - 1) / k
            (k == length(ordered) || p[ordered[k+1]] <= theta) && break
        end
        projected[group] .= max.(Q(0), p[group] .- theta)
        sum(projected[group]) == 1 || error("finite simplex adding-up failed")
    end
    (; point=projected, loss=qnorm2(p .- projected))
end

"""A same-target finite Psi bound when known-cone certificates transfer.

This is a sufficient, checked transfer, not an assumed local asymptotic formula.
The exact cone primal yields q+t*z in the original RUM hull when t*sum(mass)<=1.
The exact dual n+t*y must support ALL original RUM columns, not just critical
generators. When either check fails this function returns nothing: the draw
cannot be omitted or treated as a full finite-statistic calculation.
"""
function finite_gap_bound(cone::KnownFaceCone, g, t, gap)
    gq, t = Q.(g), Q(t)
    t > 0 || error("finite step must be positive")
    rum = gap.rum
    length(rum.primal) == length(cone.q) && !isempty(rum.masses) ||
        error("finite transfer requires saved exact cone primitives")
    t * sum(rum.masses) <= 1 || return nothing
    z = rum.primal
    dual = 2qdot(gq, rum.dual) - qnorm2(rum.dual) >= 0 ? rum.dual : zeros(Q, length(gq))
    finite_dual = cone.n .+ t .* dual
    all(<=(0), ray_prices(finite_dual, cone; indices=collect(axes(cone.A, 2)))) || return nothing
    target = cone.q .+ cone.n .+ t .* gq
    candidate = cone.q .+ t .* z
    all(candidate .>= 0) || error("finite hull mixture became negative")
    finite_simplex = product_simplex_projection(target, cone.groups)
    lower_rum = max(Q(0), 2qdot(finite_dual, target .- cone.q) - qnorm2(finite_dual))
    upper_rum = min(qnorm2(target .- candidate), qnorm2(target .- cone.q))
    lower_rum <= upper_rum || error("finite transferred weak duality failed")
    lower = max(Q(0), lower_rum - finite_simplex.loss)
    upper = upper_rum - finite_simplex.loss
    lower <= upper || error("finite transferred nested-distance bound failed")
    normal_baseline = qnorm2(cone.n) + 2t*qdot(cone.n, gq)
    simplex_local_identity = finite_simplex.loss == normal_baseline + t^2 * gap.simplex.loss
    (; lower, upper, midpoint=Float64((lower+upper)/2),
       simplex_local_identity, primal_mixture_mass=t*sum(rum.masses),
       maximum_full_RUM_normal_price=maximum(ray_prices(finite_dual, cone;
           indices=collect(axes(cone.A, 2)))))
end

